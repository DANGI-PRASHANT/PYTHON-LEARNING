# simple example of tuples:

nums = (1,2,3,4,5,6,7,8,9,0)
fruits = ("apple","banana","orange","pineapple")

print(type(nums))
print(type(fruits))

print(nums)
print(fruits)


# tuples without small brackets:

num = 1,2,3,4,5
fruits_01 = "apple" , "banana"

print(type(num))
print(type(fruits_01))

print(num)
print(fruits_01)


